/** Keys whose text is the same in both languages (a language's own name; an example address). */
export const SAME_IN_JA = Object.freeze(['lang.ja', 'lang.en', 'sharing.hostPlaceholder']);
/** Names that stay in Latin letters inside Japanese text. */
export const PROPER_NOUNS = Object.freeze(['Sumika', 'SSP', 'SHIORI', 'SAORI', 'YAYA', 'AYA', 'JSON', 'URL', 'HTML',
  'CORS', 'FTP', 'Explorer', 'Finder', 'Windows', 'OneDrive']);

/** 'ja' | 'en' for a language code, else null. */
export function uiLang(v) {
  const s = String(v ?? '').trim().toLowerCase();
  return LANGS.includes(s) ? s : null;
}

/** Whether the table has a key. */
export const has = key => Object.prototype.hasOwnProperty.call(STRINGS.en, key);

/** The raw string of `lang` (English when the language is unknown, the key when the key is), {parameters} unfilled. */
export function template(key, lang = 'en') {
  const table = STRINGS[uiLang(lang) || 'en'];
  return table[key] ?? STRINGS.en[key] ?? key;
}

/** A parameter's text: the caller's value, else PARAMS', else undefined. */
export function paramText(params, k) {
  const v = params && params[k] !== undefined && params[k] !== null ? params[k] : PARAMS[k];
  return v === undefined || v === null ? undefined : String(v);
}

/**
 * A string of `lang` with {name} parameters filled in from `params`, then from PARAMS; a parameter given neither way
 * stays visible.
 */
export function t(key, lang = 'en', params = null) {
  return template(key, lang).replace(/\{(\w+)\}/g, (m, k) => paramText(params, k) ?? m);
}

/** `${key}.one` for 1, else `${key}.many`, with {n}. */
export function plural(key, n, lang = 'en', params = null) {
  return t(`${key}.${n === 1 ? 'one' : 'many'}`, lang, { n, ...params });
}

/** A list in running text: "a, b" / "a、b". */
export function joinList(items, lang = 'en') {
  return [...items].map(String).join(uiLang(lang) === 'ja' ? '、' : ', ');
}

/** An optional detail in parentheses: '' when there is none. */
const paren = (v, lang) => (v === undefined || v === null || v === '' ? '' : uiLang(lang) === 'ja' ? `（${v}）` : ` (${v})`);

/** A finding's {exit} code as its `code.<code>.exit` text, else null. */
const exitText = (code, p, lang) => (p.exit === undefined || p.exit === null ? null : t(`code.${code}.exit`, lang, { exit: p.exit }));

// What some codes' texts say about a parameter beyond its value (an empty part when there is nothing to say).
const PREP = {
  'note.compared': (p, lang) => ({ kept: p.kept ? t('code.note.compared.kept', lang, { n: p.kept }) : '' }),
  'note.undeleteMask': (p, lang) => ({
    hits: Array.isArray(p.hits) && p.hits.length
      ? t('code.note.undeleteMask.hits', lang, { hits: joinList(p.hits, lang) }) : t('code.note.undeleteMask.none', lang),
  }),
  'busy': (p, lang) => ({ job: t(has(`job.${p.kind}`) ? `job.${p.kind}` : 'job.other', lang) }),
  'bad-request': (p, lang) => ({ detail: paren(p.detail, lang) }),
  // {exit}: the code a part of the program ended with, said as a code (the log names the part)
  'job-crashed': (p, lang) => ({ error: paren(p.error || exitText('job-crashed', p, lang), lang) }),
  'no-picker': (p, lang) => ({ error: paren(p.error || exitText('no-picker', p, lang), lang) }),
  'bundle-stale': (p, lang) => ({ file: p.file ? t('code.bundle-stale.file', lang, { file: p.file }) : '' }),
  'read-only': (p, lang) => ({
    why: has(`code.${p.reason}`) ? t(`code.${p.reason}`, lang, findingParams(p.reason, p, lang)) : String(p.reason ?? ''),
  }),
};

/** The parameters PREP makes that the program does not send (its strings test allows them). */
export const DERIVED_PARAMS = Object.freeze({ busy: ['job'], 'read-only': ['why'] });

/** The parameters of a finding as its text shows them: lists joined, a nested code (`problem`) translated. */
export function findingParams(code, params, lang = 'en') {
  const out = {};
  for (const [k, v] of Object.entries(params || {})) {
    if (Array.isArray(v)) out[k] = joinList(v, lang);
    else if (k === 'problem' && typeof v === 'string' && has(`code.${v}`)) out[k] = t(`code.${v}`, lang);
    else out[k] = v;
  }
  const prep = PREP[code];
  return prep ? { ...out, ...prep(params || {}, lang) } : out;
}

/** The code of a finding: {code}, a refusal's older {why}, or a plain code string. */
export function findingCode(f) {
  if (typeof f === 'string') return f;
  return f ? (f.code ?? f.why ?? null) : null;
}

/** Whether the page can say a finding in its own words (else it shows the program's English message). */
export const knownFinding = f => {
  const code = findingCode(f);
  return typeof code === 'string' && has(`code.${code}`);
};

/**
 * A finding as text in `lang`: {code, params?, message?} (an API error, a problem, a left-out file, a refusal), or a
 * code string. An unknown code shows the English `message` the program sent with it.
 */
export function findingText(f, lang = 'en') {
  if (f == null) return '';
  const code = findingCode(f);
  if (typeof code === 'string' && has(`code.${code}`)) {
    return t(`code.${code}`, lang, findingParams(code, typeof f === 'object' ? f.params : null, lang));
  }
  if (typeof f === 'string') return f;
  if (typeof f.message === 'string' && f.message) return f.message;
  if (typeof f.why === 'string' && f.why && f.why !== code) return f.why;      // a left-out file's English reason
  return code == null ? '' : String(code);
}
