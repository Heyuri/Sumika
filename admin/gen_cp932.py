"""Generate admin/core/cp932-table.mjs: the decode tables of Python's cp932 and cp437 codecs, for the admin core's
Python-exact text reading (admin/core/text.mjs: index_site.py read_text's cp932 with errors='replace', add_ghost.py
zip_name's strict cp932 and zipfile's cp437).

usage: python -I admin/gen_cp932.py [OUT.mjs]        (default: admin/core/cp932-table.mjs)

The cp932 tables are engines/common/gen_cp932.py tables() (Python's codec, checked there against Windows'
MultiByteToWideChar(932) with --verify): the bytes 0x80-0xFF that are no lead byte, and every lead/trail pair (60 lead
bytes, trails 0x40-0xFC; 0 = invalid). Node's TextDecoder('shift_jis') cannot stand in: it is ICU's ibm-943 (0x1A, 0x1C
and 0x7F rotated, 0x80 an error), Deno's and Bun's are WHATWG's, and none fails or replaces as Python does.
tests/admin/core.test.mjs compares the module's decoder with Python's codec on every 1- and 2-byte sequence.
"""
import base64, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'engines', 'common'))
import gen_cp932                                    # noqa: E402 (tables() only; it writes nothing on import)


def b64(units):
    data = base64.b64encode(struct.pack(f'<{len(units)}H', *units)).decode('ascii')
    return '\n'.join(f"  '{data[i:i + 112]}'," for i in range(0, len(data), 112))


def main(argv):
    out = argv[0] if argv else os.path.join(HERE, 'core', 'cp932-table.mjs')
    dec, single, _ = gen_cp932.tables()
    assert len(dec) == 60 * 189
    hi = [single.get(b, 0) for b in range(0x80, 0x100)]
    cp437 = [ord(bytes([b]).decode('cp437')) for b in range(0x80, 0x100)]
    text = '\n'.join([
        '// generated by admin/gen_cp932.py from Python\'s cp932 and cp437 codecs -- do not edit',
        '// (engines/common/gen_cp932.py tables(): checked against Windows\' MultiByteToWideChar(932) there)',
        '',
        '/** cp932, bytes 0x80..0xFF that are no lead byte (0 = a lead byte): little-endian UTF-16 units, base64 */',
        'export const CP932_SINGLE_HI = [',
        b64(hi),
        "].join('');",
        '',
        '/** cp932, [lead index (0x81..0x9F, 0xE0..0xFC)][trail - 0x40] for trails 0x40..0xFC, 0 = invalid: the same */',
        'export const CP932_DBCS = [',
        b64(dec),
        "].join('');",
        '',
        '/** cp437, bytes 0x80..0xFF (zipfile\'s name encoding without the UTF-8 flag): the same */',
        'export const CP437_HI = [',
        b64(cp437),
        "].join('');",
        '',
    ])
    with open(out, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)
    print(f'{out}: cp932 dbcs {sum(1 for u in dec if u)}, single {sum(1 for u in hi if u)}; cp437 128')


if __name__ == '__main__':
    main(sys.argv[1:])
